def task_5(n: int):
    """Задача 5: Строка-описание вида «отрицательное четное число», «нулевое число» и т. д."""
    if n == 0:
        return "нулевое число"
    sign = "положительное" if n > 0 else "отрицательное"
    parity = "четное" if n % 2 == 0 else "нечетное"
    return f"{sign} {parity} число"

def task_6(n: int):
    """Задача 6: Число 1-999 -> «четное двузначное число», «нечетное трехзначное число» и т. д."""
