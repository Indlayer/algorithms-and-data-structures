import math

def task_1(a: int, b: int):
    """Задача 1: Если A != B, присвоить каждой max(A, B), иначе 0."""
    if a != b:
        val = max(a, b)
        return val, val
    else:
        return 0, 0

def task_2(a: float, b: float, c: float):
    """Задача 2: Сумма двух наибольших из трех чисел."""
    # Если сложить все три и вычесть наименьшее, получим сумму двух наибольших
    return (a + b + c) - min(a, b, c)

def task_3(xa: float, ya: float, xb: float, yb: float, xc: float, yc: float):
    """Задача 3: Какая из точек (B или C) ближе к A, и расстояние до нее."""
    dist_ab = math.sqrt((xb - xa) ** 2 + (yb - ya) ** 2)
    dist_ac = math.sqrt((xc - xa) ** 2 + (yc - ya) ** 2)
    if dist_ab < dist_ac:
        return "B", (xb, yb), dist_ab
    elif dist_ac < dist_ab:
        return "C", (xc, yc), dist_ac
    else:
        return "Равноудалены", ((xb, yb), (xc, yc)), dist_ab

